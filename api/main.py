@app.get("/health", response_model=HealthResponse, tags=["ops"])
def health() -> HealthResponse:
    """Dependency-aware readiness check.

    Reports 'degraded' rather than failing, so an orchestrator can distinguish
    'the process is up but Qdrant is unreachable' from 'the process is dead'.
    """
    checks: dict = {}

    checks["anthropic_key"] = bool(os.getenv("ANTHROPIC_API_KEY"))
    checks["openai_key"] = bool(os.getenv("OPENAI_API_KEY"))

    try:
        checks["database"] = _db().count_patients() >= 0
    except Exception as e:
        checks["database"] = f"error: {str(e)[:80]}"

    # Vector store. In SERVER mode we really connect. In LOCAL (embedded) mode we
    # only stat the directory: opening an embedded store loads ~49k points (slow)
    # and, worse, CREATES the directory if absent — so a health probe on a runner
    # would leave a stray data/qdrant_storage behind. Same side-effect trap as the
    # eval harness creating an empty SQLite file in CI.
    try:
        from vector_store.client import QDRANT_PATH, is_server_mode
        if is_server_mode():
            from vector_store.client import get_qdrant_client
            names = [c.name for c in get_qdrant_client().get_collections().collections]
            checks["vector_store"] = {"mode": "server", "collections": names}
        else:
            exists = os.path.isdir(QDRANT_PATH)
            checks["vector_store"] = ({"mode": "embedded", "path": QDRANT_PATH}
                                      if exists else f"error: no store at {QDRANT_PATH}")
    except Exception as e:
        checks["vector_store"] = f"error: {str(e)[:80]}"

    ok = (checks["anthropic_key"] and checks["openai_key"]
          and checks["database"] is True
          and isinstance(checks["vector_store"], dict))
    return HealthResponse(status="ok" if ok else "degraded", checks=checks)


