"""
FastAPI service layer — api/main.py

Exposes the agent pipeline over HTTP so it is consumable by anything, not just
the Streamlit UI. The UI becomes one client among several rather than the only
way in.

DESIGN: this is an ADAPTER, not a second implementation.
Every endpoint delegates to the same functions the UI uses —
`graph.pipeline.answer_query` and `ingestion.sqlite_loader.MedDocDB`. That is
deliberate: the Streamlit app previously grew a private copy of the pipeline
invocation which silently bypassed all observability, and collapsing it was part
of the instrumentation work. A service layer that re-implemented the pipeline
would recreate exactly that bug, one layer up.

Run:
    uvicorn api.main:app --reload --port 8000
    open http://localhost:8000/docs        # interactive OpenAPI docs
"""

from __future__ import annotations

import logging
import os
import time

from dotenv import load_dotenv
from fastapi import FastAPI, HTTPException, Request, status
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import JSONResponse

load_dotenv(dotenv_path=os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), ".env"),
            override=True)

from api.schemas import (  # noqa: E402
    EvidenceItem,
    FeedbackRequest,
    FeedbackResponse,
    HealthResponse,
    PatientDetail,
    PatientSummary,
    QueryMetrics,
    QueryRequest,
    QueryResponse,
)

logger = logging.getLogger(__name__)

DB_PATH = "data/meddocai.db"

app = FastAPI(
    title="MedDocAI API",
    version="1.0.0",
    description=(
        "Source-grounded answers about medications, health conditions, and Medicaid "
        "policy, produced by a 6-agent LangGraph pipeline with corrective-RAG "
        "self-correction.\n\n"
        "**Synthetic data only** — patient records are generated by Synthea. "
        "Answers are for demonstration and are not medical advice."
    ),
)

# The UI may be served from a different origin than the API.
app.add_middleware(
    CORSMiddleware,
    allow_origins=os.getenv("MEDDOCAI_CORS_ORIGINS", "*").split(","),
    allow_methods=["GET", "POST"],
    allow_headers=["*"],
)


def _db():
    from ingestion.sqlite_loader import MedDocDB
    return MedDocDB(DB_PATH)


@app.middleware("http")
async def add_timing_header(request: Request, call_next):
    """Server-side latency on every response — cheap, and useful to any client."""
    t0 = time.perf_counter()
    response = await call_next(request)
    response.headers["X-Process-Time-Ms"] = str(int((time.perf_counter() - t0) * 1000))
    return response


@app.exception_handler(Exception)
async def unhandled_exception_handler(request: Request, exc: Exception):
    """Never leak a stack trace (it can contain file paths and prompt fragments)."""
    logger.exception("Unhandled error on %s", request.url.path)
    return JSONResponse(status_code=500, content={"detail": "Internal server error"})


