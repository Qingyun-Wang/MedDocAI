@app.get("/patients", response_model=list[PatientSummary], tags=["patients"])
def list_patients(limit: int = 100) -> list[PatientSummary]:
    """The demo patient roster — the API equivalent of the sidebar selector."""
    try:
        rows = _db().list_patients(limit=limit)
    except Exception as e:
        raise HTTPException(status_code=503, detail=f"Database unavailable: {str(e)[:120]}")

    # NOTE: list_patients() selects only the roster columns — no clinical JSON — so
    # counts are NOT available here and must not be faked as zero. Clients that need
    # them call GET /patients/{id}.
    return [
        PatientSummary(
            patient_id=r["patient_id"],
            name=r.get("name", ""),
            age=r.get("age"),
            gender=r.get("gender"),
            has_summary=bool(r.get("has_summary")),
        )
        for r in rows
    ]


@app.get("/patients/{patient_id}", response_model=PatientDetail, tags=["patients"])
def get_patient(patient_id: str) -> PatientDetail:
    try:
        row = _db().get_patient(patient_id)
    except Exception as e:
        raise HTTPException(status_code=503, detail=f"Database unavailable: {str(e)[:120]}")
    if not row:
        raise HTTPException(status_code=404, detail=f"No patient with id {patient_id}")

    meds = row.get("medications_json") or []
    labs = row.get("labs_json") or []
    active = [m for m in meds if m.get("status") == "active"]
    abnormal = [l for l in labs if l.get("is_abnormal")]
    return PatientDetail(
        patient_id=row["patient_id"],
        name=row.get("name", ""),
        age=row.get("age"),
        gender=row.get("gender"),
        n_conditions=len(row.get("conditions_json") or []),
        n_active_medications=len(active),
        n_abnormal_labs=len(abnormal),
        conditions=row.get("conditions_json") or [],
        medications=active,
        abnormal_labs=abnormal,
        summary_md=row.get("summary_md"),
    )


