@app.post("/query", response_model=QueryResponse, tags=["query"],
          responses={404: {"description": "patient_id not found"}})
def query(req: QueryRequest) -> QueryResponse:
    """Answer one question through the full agent pipeline.

    Returns the answer twice on purpose: `answer` is the generated text, while
    `final_answer` adds the sources block and safety disclaimers. A client
    rendering to end users should show `final_answer`; a client scoring quality
    wants `answer`, since the deterministic disclaimers are not grounded in the
    retrieved evidence and would distort a faithfulness measurement.
    """
    patient_context = None
    if req.patient_id:
        try:
            patient_context = _db().get_patient(req.patient_id)
        except Exception as e:
            raise HTTPException(status_code=503, detail=f"Database unavailable: {str(e)[:120]}")
        if not patient_context:
            raise HTTPException(status_code=404, detail=f"No patient with id {req.patient_id}")

    from graph.pipeline import answer_query
    try:
        final = answer_query(
            req.question,
            patient_context=patient_context,
            user_role=req.user_role,
            max_iterations=req.max_iterations,
            conversation_history=[t.model_dump() for t in req.conversation_history],
        )
    except Exception as e:
        logger.exception("Pipeline failed")
        raise HTTPException(status_code=502, detail=f"Pipeline error: {str(e)[:200]}")

    evidence = [
        EvidenceItem(source=e.source, title=e.title, text=e.text,
                     score=e.score, citation=e.citation)
        for e in final.get("filtered_evidence", [])
    ]
    m = final.get("metrics") or {}
    return QueryResponse(
        query_id=final.get("query_id", ""),
        answer=final.get("answer", ""),
        final_answer=final.get("final_answer", final.get("answer", "")),
        citations=final.get("citations", []),
        evidence=evidence,
        disclaimers=final.get("disclaimers", []),
        intent=final.get("intent", ""),
        iterations=final.get("iteration", 0),
        review_passed=bool(final.get("review_passed", False)),
        sub_queries=final.get("sub_queries", []) or [],
        trace=final.get("trace", []),
        metrics=QueryMetrics(
            llm_calls=m.get("llm_calls", 0),
            total_tokens=m.get("total_tokens", 0),
            cost_usd=m.get("cost_usd"),
            total_latency_ms=m.get("total_latency_ms", 0.0),
        ),
    )


