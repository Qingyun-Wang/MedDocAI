@app.post("/feedback", response_model=FeedbackResponse, tags=["feedback"],
          status_code=status.HTTP_201_CREATED)
def submit_feedback(req: FeedbackRequest) -> FeedbackResponse:
    """Record a thumbs verdict on a previous answer.

    Keyed by query_id, so re-rating replaces rather than double-counting, and the
    row joins back to that query's cost/latency metrics. Thumbs-down rows are
    harvested into candidate eval questions by scripts/feedback_to_eval.py.
    """
    db = _db()
    # Backfill the denormalised fields from this query's metrics row. An HTTP
    # client only sends a query_id, but a feedback row with no question text is
    # useless downstream — the exporter cannot build an eval candidate from it.
    # This is exactly the join query_id exists for.
    ctx = {}
    try:
        row = db.get_query_metrics(req.query_id) or {}
        ctx = {
            "question": row.get("query", ""),
            "intent": row.get("intent", ""),
            "user_role": row.get("user_role", ""),
            "patient_id": row.get("patient_id"),
            "session_id": row.get("session_id"),
            "review_passed": bool(row.get("review_passed")),
            "n_evidence": row.get("n_evidence") or 0,
        }
    except Exception:
        pass                         # a missing metrics row must not block the rating

    try:
        db.save_feedback(
            query_id=req.query_id,
            rating=req.rating,
            comment=req.comment,
            **ctx,
        )
    except ValueError as e:
        raise HTTPException(status_code=422, detail=str(e))
    except Exception as e:
        raise HTTPException(status_code=503, detail=f"Could not record feedback: {str(e)[:120]}")
    return FeedbackResponse(recorded=True, query_id=req.query_id, rating=req.rating)


@app.get("/feedback/stats", tags=["feedback"])
def feedback_stats() -> dict:
    """Aggregate thumbs counts — the improvement loop at a glance."""
    try:
        counts = _db().feedback_counts()
    except Exception as e:
        raise HTTPException(status_code=503, detail=f"Database unavailable: {str(e)[:120]}")
    total = counts["up"] + counts["down"]
    return {
        **counts,
        "total": total,
        "positive_rate": round(counts["up"] / total, 3) if total else None,
    }
